package sortament

// Курируемый локальный справочник масс 1 пог. метра, собранный вручную с карточек
// 23met.ru (папка проекта «Скриншоты с массой») под эталонный комплект профилей
// заказчика. Нужен как офлайн-фолбэк: при пачке запросов 23met отдаёт 429, и строки
// молча получают «Нет данных». Сид перекрывает это — масса берётся локально по
// наименованию профиля (марке), без сети.
//
// Ключ — нормализованная марка (как её строит Normalize), значение — масса 1 пог.
// метра, кг. Ключи собираются через Normalize/ExpandAngleMark, поэтому гарантированно
// совпадают с тем, что вычисляет Resolver.Resolve, — без ручных кириллических литералов
// «Х»/«Б». Приоритет в Resolve: запись справочника (БД, в т.ч. ручная правка) → этот
// сид → 23met, так что правка специалиста всегда побеждает сид.

// seedEntry — сырьё марки (как в спецификации) и масса 1 пог. метра, кг.
type seedEntry struct {
	raw  string
	mass float64
}

// seedSource — эталонные значения «Масса 1 м» с карточек 23met.ru.
var seedSource = []seedEntry{
	// Двутавры (балки), ГОСТ 26020-83.
	{"26Б1", 28.0},
	{"23Б1", 25.8},
	{"30Б1", 32.0},
	{"40Б1", 56.6},
	// Гнутосварные замкнутые профили (трубы кв./прямоуг.), ГОСТ 30245-2003.
	{"Тр 160х5", 23.83},
	{"Тр 120х3", 10.84},
	{"Тр 120х80х3", 8.96},
	{"Тр 60х4", 6.82},
	// Швеллер гнутый 120х60х4.
	{"[120х60х4", 6.96},
	// Уголки равнополочные, ГОСТ 8509-93. Двухчисловую запись (75х6) Resolver
	// разворачивает в трёхчисловую (75Х75Х6) — добавляем оба варианта записи.
	{"L 75х6", 6.89},
	{"75х6", 6.89},
	{"L 50х5", 3.77},
	{"50х5", 3.77},
}

// seedMassPerMeter — мапа нормализованная_марка → масса 1 пог. метра.
var seedMassPerMeter = buildSeed()

func buildSeed() map[string]float64 {
	m := make(map[string]float64, len(seedSource)*2)
	for _, e := range seedSource {
		k := Normalize(e.raw)
		if k == "" {
			continue
		}
		m[k] = e.mass
		// Покрываем и развёрнутую запись равнополочного уголка (75Х6 → 75Х75Х6),
		// если чертёж записал марку двумя числами.
		if exp := ExpandAngleMark(k); exp != k {
			m[exp] = e.mass
		}
	}
	return m
}

// seedMass возвращает массу 1 пог. метра из курируемого справочника по
// нормализованной марке. ok=false — марки в сиде нет.
func seedMass(mark string) (float64, bool) {
	v, ok := seedMassPerMeter[mark]
	return v, ok
}
