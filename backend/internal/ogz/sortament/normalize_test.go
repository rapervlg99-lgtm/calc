package sortament

import "testing"

func TestNormalize(t *testing.T) {
	cases := []struct {
		in, want string
	}{
		{"35Б2", "35Б2"},
		{" 35б2 ", "35Б2"},
		{"Двутавр 35Б2 ГОСТ 26020-83", "35Б2"},
		{"35Б2 С255", "35Б2"},
		{"Швеллер 20П ГОСТ 8240-97", "20П"},
		{"Уголок 75x75x6", "75Х75Х6"},
		{"Труба 50х3", "50Х3"},
		{"Лист 10 ГОСТ 19903-2015", "10"},
		{"балка 35Ш1 ст3пс", "35Ш1"},
		{"10 Б1", "10Б1"},
		{"10B1", "10Б1"}, // латинская B → кириллическая Б
		{"20P", "20П"},
		{"С255", ""},
		{"09Г2С", ""},
		{"", ""},
		{"   ", ""},
	}
	for _, c := range cases {
		if got := Normalize(c.in); got != c.want {
			t.Errorf("Normalize(%q) = %q, want %q", c.in, got, c.want)
		}
	}
}
