"""Стандарты вида «СТО АСЧМ 20-93» (обозначение между видом и номером).

На «Ведомости» группа двутавров и швеллеров подписана «… СТО АСЧМ 20-93».
Шаблон стандарта требовал номер сразу после вида («ГОСТ 8240-97») и такие СТО не
ловил: профильный ГОСТ не попадал в результат, и масса подбиралась не по
стандарту листа, а по формуле — строка уходила в «Требует проверки».
"""
from ocrpdf.normalizer import GOST_RE, _canon_standard


def standards(text: str) -> list:
    return [_canon_standard(m) for m in GOST_RE.finditer(text)]


def test_sto_with_letter_designation():
    assert standards("Двутавры горячекатаные с параллельными гранями полок СТО АСЧМ 20-93") == [
        "СТО АСЧМ 20-93"
    ]
    assert standards("Швеллеры горячекатаные СТО АСЧМ 20-93") == ["СТО АСЧМ 20-93"]
    assert standards("СТО 36554501-006-2006") == ["СТО 36554501-006-2006"]


def test_plain_gost_is_not_changed():
    assert standards("Трубы стальные квадратные ГОСТ 30245-2012") == ["ГОСТ 30245-2012"]
    assert standards("Прокат листовой горячекатаный ГОСТ 19903-74*") == ["ГОСТ 19903-74"]
    assert standards("Двутавры по ГОСТ Р 57837-2017") == ["ГОСТ Р 57837-2017"]
    assert standards("Арматура ТУ 14-1-5254-93") == ["ТУ 14-1-5254-93"]


def test_group_with_steel_grade_and_profile_standard():
    """«С255 по ГОСТ 27772-2021» и профильный ГОСТ в одной строке — оба на месте."""
    got = standards("С255-5 по ГОСТ 27772-2021, двутавр СТО АСЧМ 20-93")
    assert got == ["ГОСТ 27772-2021", "СТО АСЧМ 20-93"], got
