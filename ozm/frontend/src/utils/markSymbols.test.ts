import { describe, expect, it } from 'vitest'
import { cleanMark } from './ocrImport'

/**
 * Значок вида профиля, попавший в обозначение из текстового слоя.
 *
 * В «Ведомость.pdf» символ двутавра записан цифрой — размер приходил как
 * «1 50Ш4» вместо «I 50Ш4». `cleanMark` снимал `□ ∟ ⌶ I | L [`, но не цифру,
 * поэтому марка не находилась в сортаменте и все 11 строк двутавров уходили
 * в ручной ввод («Нужен ввод массы»), хотя «50Ш4», «45Ш4», «40Ш2» там есть.
 */
describe('cleanMark: значок профиля перед обозначением', () => {
  it('снимает значок двутавра, прочитанный цифрой или буквой', () => {
    expect(cleanMark('1 50Ш4')).toBe('50Ш4')
    expect(cleanMark('1 45Ш4')).toBe('45Ш4')
    expect(cleanMark('l 40Ш2')).toBe('40Ш2')
    expect(cleanMark('I 50Ш4')).toBe('50Ш4')
    expect(cleanMark('1 □250х6')).toBe('250х6')
  })

  it('не трогает настоящие обозначения, начинающиеся с цифры', () => {
    expect(cleanMark('160х5')).toBe('160х5')
    expect(cleanMark('12.5')).toBe('12.5')
    expect(cleanMark('250х6')).toBe('250х6')
    expect(cleanMark('1.5')).toBe('1.5')
  })

  it('сочетается со снятием кода детали и значков швеллера', () => {
    expect(cleanMark('1 50Ш4 (214-202-0103-0002)')).toBe('50Ш4')
    expect(cleanMark('[ 22П')).toBe('22П')
  })
})
