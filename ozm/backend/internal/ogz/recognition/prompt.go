package recognition

// Prompt — инструкция vision-модели на извлечение строк спецификации металлопроката
// с РАЗБИВКОЙ массы по типам конструкций. Сформулирована на over-include (ТЗ §14):
// сомнительные строки включаются с uncertain=true, а не отбрасываются. Схема ответа
// совпадает с modelRow.
func Prompt() string {
	return `Это страница со сканом таблицы "Спецификация металлопроката" (русский чертёж).
В таблице масса металла каждого элемента РАЗНЕСЕНА ПО СТОЛБЦАМ "Масса металла по
элементам конструкций, т": например "Колонны/Стойки", "Балки", "Связи", "Прогоны",
"Фахверк" и крайний столбец "Общая масса". Один профиль может иметь массу сразу в
нескольких столбцах конструкций.

Извлеки ВСЕ строки таблицы, которые видишь, включая строки-итоги ("Всего профиля",
"Всего металла", "Всего стали").

Для каждой строки верни поля:
  - "наименование": группа профиля из первого столбца (например "Двутавры стальные
    горячекатаные по ГОСТ 57837-2017", "Уголки стальные...", "Прокат листовой...").
    Для строки данных повторяй наименование её группы.
  - "гост_профиля": номер ГОСТ/сортамента профиля из наименования (например
    "ГОСТ 57837-2017", "ГОСТ 8509-93"). Если в наименовании нет ГОСТ — null.
  - "марка_стали": марка стали, если указана в строке (например "С255", "С345").
    Если нет — null.
  - "профиль": номер или размер профиля (например "30Ш1", "50Б1", "40У", "24П",
    "L63x5", "t10"). В марке часто есть КИРИЛЛИЧЕСКАЯ буква типоразмера: Б (балка),
    Ш (широкополочный), К (колонный), М/Д, У (швеллер с уклоном полок), П (швеллер
    с параллельными полками), Г (гнутый). НЕ путай букву с цифрой: «40У» — это
    сорок-У, а НЕ «409»; «24П» — это НЕ «241». Если последний символ читается
    нечётко (буква или цифра?) — перепиши как видишь и поставь "uncertain": true,
    чтобы специалист проверил вручную. Для строки-итога укажи "Всего профиля" /
    "Всего стали" / "Всего металла".
  - "номер_пп": номер позиции (п/п) строки, если он есть в таблице; иначе null.
  - "конструкции": МАССИВ объектов по столбцам конструкций, где у этого профиля есть
    масса. Каждый объект: {"тип": "<заголовок столбца, например Колонны/Стойки>",
    "масса_т": <число>}. Включай ТОЛЬКО столбцы с ненулевой массой. Если у строки
    нет разбивки по конструкциям (например листовой прокат) — верни пустой массив [].
    ВАЖНО ПРО СТОЛБЦЫ: "тип" — это заголовок столбца ДОСЛОВНО, как он напечатан в
    шапке таблицы ("Подкрановые конструкции", "Колонны/Стойки", "Связи по колоннам").
    НЕ объединяй и НЕ переименовывай разные столбцы: «Подкрановые конструкции» — это
    отдельная конструкция, её НЕЛЬЗЯ класть в «Колонны/Стойки». Масса должна
    оставаться строго под своим столбцом. Если столбец незнакомый — всё равно
    перепиши его заголовок дословно, ничего не подменяя.
  - "общая_масса_т": значение из крайнего столбца "Общая масса", в тоннах (число).
    Для листового проката — общая масса строки.
  - "uncertain": true, если хоть в одном поле строки ты не уверен; иначе false.

ВНИМАТЕЛЬНО ЧИТАЙ ЧИСЛА:
  - Десятичная точка важна: "1.90" — это 1.9, а не 19. Считывай ровно столько цифр,
    сколько видишь в ячейке: не добавляй и не убирай нули.
  - Пробел/неразрывный пробел между тройками цифр ("51 500") — разделитель разрядов,
    а не новая цифра; это 51500, а НЕ 515000.
  - Сумма масс по конструкциям строки должна совпадать с её "общая_масса_т". Если не
    сходится — перечитай числа и поставь "uncertain": true.
  - Если число выглядит подозрительно большим относительно соседних строк той же
    группы — перечитай его и поставь "uncertain": true.

ВАЖНО:
  - Ничего не пропускай. Если сомневаешься в строке — всё равно включи её с "uncertain": true.
  - Не выдумывай значения. Если ячейка пустая — оставь null.
  - Ответ — ТОЛЬКО валидный JSON, без пояснений, строго в виде:
    {"rows":[{"наименование":"...","гост_профиля":"...","марка_стали":null,"профиль":"...","номер_пп":"...","конструкции":[{"тип":"Колонны/Стойки","масса_т":2.38},{"тип":"Балки","масса_т":16.41}],"общая_масса_т":18.79,"uncertain":false}]}`
}
